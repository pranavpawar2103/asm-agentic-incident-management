"""Resolution agent: knowledge base chunks (table kb_chunks, created by backend/db/scripts/04_create_kb_chunks.sql).

The `fts` column is generated by the database and is not mapped here.
"""

from datetime import UTC, datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import BigInteger, DateTime, Integer, String, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from app.core.config import settings
from app.db.session import Base


def utcnow() -> datetime:
    return datetime.now(UTC)


class KBChunk(Base):
    """One chunk of a knowledge base runbook, with its contextual text and (once generated) its embedding."""

    __tablename__ = "kb_chunks"
    __table_args__ = (UniqueConstraint("source_path", "chunk_index", name="uq_kb_chunks_source_index"),)

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    source_path: Mapped[str] = mapped_column(String(255), nullable=False)
    chunk_index: Mapped[int] = mapped_column(Integer, nullable=False)
    app: Mapped[str] = mapped_column(String(128), nullable=False)
    app_id: Mapped[str | None] = mapped_column(String(32))
    kb_id: Mapped[str | None] = mapped_column(String(32))
    section_type: Mapped[str] = mapped_column(String(16), nullable=False)
    title: Mapped[str] = mapped_column(Text, nullable=False)
    heading_path: Mapped[str] = mapped_column(Text, nullable=False)
    support_group: Mapped[str | None] = mapped_column(String(128))
    criticality_tier: Mapped[str | None] = mapped_column(String(16))
    authority: Mapped[str] = mapped_column(String(16), nullable=False, default="primary")
    content: Mapped[str] = mapped_column(Text, nullable=False)
    context: Mapped[str] = mapped_column(Text, nullable=False, default="")
    content_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    embedding: Mapped[list[float] | None] = mapped_column(Vector(settings.EMBEDDING_DIM))
    embedding_model: Mapped[str | None] = mapped_column(String(128))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, nullable=False)
